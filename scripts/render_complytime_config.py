#!/usr/bin/env python3
"""Render .complytime/complytime.yaml from the control domains in gemara/*/.

complyctl needs every policy, and the targets that use it, listed in its
config. Generating that list means adding a domain (gemara/<domain>/policy.yaml
plus its Rego) needs no config or Makefile edit.

    render_complytime_config.py [--registry http://localhost:5050/x]
        [--policy-version v0.1.0] [--complypack-version v0.1.0] [--out FILE]

Defaults match the Makefile (REGISTRY, POLICY_VERSION, COMPLYPACK_VERSION).
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
# GENERATED by scripts/render_complytime_config.py (make config). Do not edit.
#
# complyctl runtime config. The OCI references below must be published first
# (make publish-policy / make publish-complypack) and must match what you
# pushed.
#
# Points at a local-only registry by default (matching the Makefile's REGISTRY
# default) so nothing here touches a public registry or real AWS out of the
# box -- see docs/credentials.md for how to run that local registry and S3
# locker, and for pointing this at a real registry once the project has one.
"""

TARGET = """\

# One OPA target for every AR. The opa provider evaluates every mapped Rego
# package against every file under input_path; each package only judges
# evidence carrying its own assessment_requirement, and the entrypoint fails
# the run when an AR has no evidence.
targets:
  - id: rosa-seaplane-opa
    policies:
{target_policies}
    variables:
      # Must be an absolute path (RSC_EVIDENCE_DIR set via entrypoint.py);
      # conftest reads every AR's evidence subdirectory beneath it.
      input_path: ${{RSC_EVIDENCE_DIR}}
"""


def domains(gemara_dir: Path) -> list:
    """Domain names: every gemara/<domain>/ holding a policy.yaml."""
    return sorted(p.parent.name for p in gemara_dir.glob("*/policy.yaml"))


def render(domain_names: list, registry: str, policy_version: str, complypack_version: str) -> str:
    if not domain_names:
        raise SystemExit("ERROR: no gemara/*/policy.yaml found.")
    registry = registry.rstrip("/")
    out = [HEADER, "policies:"]
    for d in domain_names:
        out += [f"  - url: {registry}/policies/{d}:{policy_version}", f"    id: {d}"]
    out += ["", "# One complypack per evaluator, carrying every domain's Rego and mapping.", "complypacks:",
            f"  - url: {registry}/complypacks/rosa-seaplane:{complypack_version}", "    id: rosa-seaplane-opa"]
    target_policies = "\n".join(f"      - {d}" for d in domain_names)
    return "\n".join(out) + "\n" + TARGET.format(target_policies=target_policies)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--registry", default="http://localhost:5050/rosa-seaplane-compliance")
    ap.add_argument("--policy-version", default="v0.1.0")
    ap.add_argument("--complypack-version", default="v0.1.0")
    ap.add_argument("--out", default=str(ROOT / ".complytime/complytime.yaml"))
    args = ap.parse_args()
    text = render(domains(ROOT / "gemara"), args.registry, args.policy_version, args.complypack_version)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
